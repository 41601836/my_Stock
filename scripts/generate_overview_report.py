"""
方向 A4: 全因子总览报告生成器
================================
从 factor_ranking.csv + factor_corr_matrix.csv + factor_clusters.csv
生成全因子总览 HTML 报告。

报告内容:
  1. 总览仪表盘 (多少个S/A/B/C，平均得分)
  2. 因子排名表 (全量，可搜索排序)
  3. 分类分析 (各分类平均得分、最佳因子)
  4. 相关性热力图 (ECharts heatmap)
  5. 聚类分析 (每簇代表因子 + 簇内成员)
  6. 独立因子池 (推荐使用的因子列表)

用法:
  python3 scripts/generate_overview_report.py
"""

import os
import sys
import argparse
import json

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, PROJECT_ROOT)

from factor_lib.registry import FACTOR_REGISTRY

