def main():
    parser = argparse.ArgumentParser(description="生成全因子总览报告")
    parser.add_argument("--ranking", type=str, default=None, help="评级 CSV 路径")
    parser.add_argument("--corr", type=str, default=None, help="相关矩阵 CSV 路径")
    parser.add_argument("--clusters", type=str, default=None, help="聚类 CSV 路径")
    parser.add_argument("--indep", type=str, default=None, help="独立因子 CSV 路径")
    parser.add_argument("--output", type=str, default=None, help="输出 HTML 路径")
    parser.add_argument("--n-clusters", type=int, default=5, help="聚类数量")
    args = parser.parse_args()

    report_dir = os.path.join(PROJECT_ROOT, "factor_test_reports")

    ranking_path = args.ranking or os.path.join(report_dir, "factor_ranking.csv")
    corr_path = args.corr or os.path.join(report_dir, "factor_corr_matrix.csv")
    clusters_path = args.clusters or os.path.join(report_dir, "factor_clusters.csv")
    indep_path = args.indep or os.path.join(report_dir, "independent_factors.csv")
    output_path = args.output or os.path.join(report_dir, "factor_overview_report.html")

    print(f"\n  生成全因子总览报告")
    print(f"  {'─' * 50}")

    # 检查文件
    for p, name in [(ranking_path, "评级"), (corr_path, "相关矩阵"), (clusters_path, "聚类")]:
        if not os.path.exists(p):
            print(f"❌ 缺少 {name} 数据: {p}")
            sys.exit(1)

    ranking_df = pd.read_csv(ranking_path)
    corr_matrix = pd.read_csv(corr_path, index_col=0)
    cluster_df = pd.read_csv(clusters_path)

    if os.path.exists(indep_path):
        indep_df = pd.read_csv(indep_path)
    else:
        print(f"  ⚠️  独立因子文件不存在，从聚类生成")
        indep_df = None  # 将在相关性脚本中生成

    path = generate_overview_report(ranking_df, corr_matrix, cluster_df, indep_df, output_path)
    print(f"\n  ✅ 报告生成: {path}")
    print(f"     因子数: {len(ranking_df)}")
    print(f"     聚类数: {args.n_clusters}")

