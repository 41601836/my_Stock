import pandas as pd

def generate_overview_report(ranking_df, corr_matrix, cluster_df, indep_df, output_path):
    """生成全因子总览 HTML 报告"""

    total_factors = len(ranking_df)
    grade_counts = ranking_df["grade"].value_counts().reindex(
        ["S", "A+", "A", "B+", "B", "C+", "C", "D"], fill_value=0
    )
    avg_score = ranking_df["total_score"].mean()
    s_count = int(grade_counts.get("S", 0))
    a_count = int(grade_counts.get("A+", 0)) + int(grade_counts.get("A", 0))
    b_count = int(grade_counts.get("B+", 0)) + int(grade_counts.get("B", 0))
    c_count = int(grade_counts.get("C+", 0)) + int(grade_counts.get("C", 0))
    d_count = int(grade_counts.get("D", 0))

    # 分类统计
    cat_stats = ranking_df.groupby("category").agg(
        n_factors=("factor", "count"),
        avg_score=("total_score", "mean"),
        avg_icir=("icir", lambda x: abs(x).mean()),
    ).sort_values("avg_score", ascending=False)

    # 星级分布数据
    stars_data = []
    for grade in ["S", "A+", "A", "B+", "B", "C+", "C", "D"]:
        count = int(grade_counts.get(grade, 0))
        if count > 0:
            stars_data.append({"grade": grade, "count": count})

    # 排名表数据
    ranking_table = []
    for _, r in ranking_df.iterrows():
        star_str = "★" * int(r["stars"]) + "☆" * (7 - int(r["stars"]))
        ranking_table.append({
            "rank": int(r["rank"]),
            "factor": r["factor"],
            "category": r["category"],
            "stars": star_str,
            "grade": r["grade"],
            "score": round(float(r["total_score"]), 2),
            "icir": round(float(r["icir"]), 4) if pd.notna(r["icir"]) else None,
            "monotonicity": round(float(r["monotonicity_score"]), 3) if pd.notna(r["monotonicity_score"]) else None,
            "perm_p": round(float(r["perm_p_value"]), 4) if pd.notna(r["perm_p_value"]) else None,
            "sharpe": round(float(r["sharpe"]), 3) if pd.notna(r["sharpe"]) else None,
            "annual_return": round(float(r["annual_return"]), 4) if pd.notna(r["annual_return"]) else None,
            "max_dd": round(float(r["max_drawdown"]), 4) if pd.notna(r["max_drawdown"]) else None,
        })

    # 相关性热力图数据 (取 top 30 因子避免图太大)
    top_factors = ranking_df.head(30)["factor"].tolist()
    top_factors = [f for f in top_factors if f in corr_matrix.index]
    corr_top = corr_matrix.loc[top_factors, top_factors]

    # 热力图数据格式: [row_idx, col_idx, value]
    heatmap_data = []
    for i, row_f in enumerate(top_factors):
        for j, col_f in enumerate(top_factors):
            val = corr_top.iloc[i, j]
            if i != j:  # 跳过对角线
                heatmap_data.append([i, j, round(float(val), 3)])

    # 聚类数据
    clusters_info = []
    for c in sorted(cluster_df["cluster"].unique()):
        factors = cluster_df[cluster_df["cluster"] == c]["factor"].tolist()
        rep_row = indep_df[indep_df["cluster"] == c]
        rep = rep_row.iloc[0]["representative"] if len(rep_row) > 0 else factors[0]
        rep_grade = ""
        rep_score = ""
        if rep in ranking_df["factor"].values:
            r = ranking_df[ranking_df["factor"] == rep].iloc[0]
            rep_grade = r["grade"]
            rep_score = round(float(r["total_score"]), 2)
        clusters_info.append({
            "cluster": int(c),
            "n_factors": len(factors),
            "representative": rep,
            "rep_grade": rep_grade,
            "rep_score": rep_score,
            "factors": factors,
        })

    # JSON 数据（供 ECharts 使用）
    stars_data_json = json.dumps(stars_data, ensure_ascii=False)
    top_factors_json = json.dumps(top_factors, ensure_ascii=False)
    heatmap_data_json = json.dumps(heatmap_data, ensure_ascii=False)
    cat_stats_json = cat_stats.reset_index().to_json(orient="records", force_ascii=False)

    # 生成 HTML
